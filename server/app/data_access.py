"""Public data-access contracts. Business code imports no SQL or filesystem adapters.

Records are ordinary business dictionaries, tracked for the lifetime of a transaction.
Successful write transactions persist changes together; exceptions roll everything back.
Records must not be retained for later writes. Read transactions never persist changes.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import datetime
from typing import Any, BinaryIO, ContextManager, Protocol

Record = dict[str, Any]

class StorageError(Exception):
    """Storage failure with no connection strings or physical paths."""

class StorageConflict(StorageError):
    """A unique constraint or concurrent update rejected the operation."""

class StorageUnavailable(StorageError):
    """Storage is currently unavailable."""


def session_key(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class SampleFilter:
    review_statuses: tuple[str, ...] | None = None
    excluded: bool | None = None
    final_cultivar_id: str | None = None
    final_class_id: str | None = None
    uploaded_from: datetime | None = None
    uploaded_to: datetime | None = None
    query: str = ""
    owner_id: str | None = None
    batch_id: str | None = None


@dataclass(frozen=True)
class RecordPage:
    items: list[Record]
    total: int


class DataTransaction(Protocol):
    """Use-case queries and tracked records; no tables, sessions or whole-store view."""
    def get_batch(self, batch_id: str) -> Record | None: ...
    def add_batch(self, record: Record) -> None: ...
    def list_batches(self, owner_id: str | None, page: int, page_size: int) -> RecordPage: ...
    def get_question(self, question_id: str) -> Record | None: ...
    def add_question(self, record: Record) -> None: ...
    def list_questions(self, owner_id: str | None, page: int, page_size: int) -> RecordPage: ...
    def get_phone_identity(self, phone_key: str) -> Record | None: ...
    def find_phone_for_user(self, user_id: str) -> Record | None: ...
    def add_phone_identity(self, record: Record) -> None: ...
    def get_sms_state(self, key: str) -> Record | None: ...
    def add_sms_state(self, record: Record) -> None: ...
    def get_user(self, user_id: str) -> Record | None: ...
    def find_user(self, username: str) -> Record | None: ...
    def users_exist(self) -> bool: ...
    def list_users(self, page: int, page_size: int) -> RecordPage: ...
    def active_superadmins(self) -> list[Record]: ...
    def add_user(self, user: Record) -> None: ...
    def get_session(self, token: str) -> Record | None: ...
    def add_session(self, token: str, record: Record) -> None: ...
    def revoke_session(self, session_id: str) -> None: ...
    def revoke_user_sessions(self, user_id: str) -> None: ...
    def get_config(self) -> Record: ...
    def list_cultivars(self) -> list[Record]: ...
    def list_classes(self) -> list[Record]: ...
    def get_cultivar(self, cultivar_id: str | None) -> Record | None: ...
    def get_class(self, class_id: str | None) -> Record | None: ...
    def seed_catalog(self, cultivars: list[Record], classes: list[Record]) -> None: ...
    def get_sample(self, sample_id: str) -> Record | None: ...
    def get_upload(self, upload_id: str) -> Record | None: ...
    def find_upload_for_image(self, image_id: str) -> Record | None: ...
    def add_collection(self, upload: Record, sample: Record) -> None: ...
    def list_samples(self, filters: SampleFilter, page: int, page_size: int) -> RecordPage: ...
    def export_samples(self, filters: SampleFilter) -> list[Record]: ...
    def get_export(self, export_id: str) -> Record | None: ...
    def add_export(self, job: Record) -> None: ...
    def list_exports(self, page: int, page_size: int) -> RecordPage: ...
    def interrupted_exports(self) -> list[Record]: ...
    def get_idempotency(self, key: str) -> Record | None: ...
    def add_idempotency(self, key: str, record: Record) -> None: ...


class MetadataStorage(Protocol):
    def initialize(self) -> None: ...
    def transaction(self, *, write: bool = True) -> ContextManager[DataTransaction]: ...
    def ping(self) -> None: ...
    def close(self) -> None: ...


class StagedFile(Protocol):
    """Private workspace: exposes a seekable stream, never a physical pathname."""
    @property
    def stream(self) -> BinaryIO: ...
    def publish(self, key: str) -> bool: ...


class FileStorage(Protocol):
    def exists(self, key: str) -> bool: ...
    def open_read(self, key: str) -> BinaryIO: ...
    def write(self, key: str, data: bytes) -> bool: ...
    def stage(self) -> ContextManager[StagedFile]: ...
    def delete(self, key: str) -> None: ...
    def ping(self) -> None: ...
